def main():
    print("=" * 80)
    print("EXTRAÇÃO & ESTRUTURAÇÃO DE CLIENTES CORPORATIVOS B2B (NÃO-HOSPITARES)")
    print(f"Critério: Empresas com no mínimo 100 colaboradores presenciais no raio de 5 km da sede")
    print(f"Sede de Referência: {CHAME_SEDE_NOME} ({CHAME_LAT}, {CHAME_LON})")
    print("=" * 80)

    # 1. Carregar catálogo oficial de pontos de táxi geocodificados (DTP)
    pontos_csv = BASE_DIR / "Novos Alvarás 2026" / "roteiro_tatico_visitas_pontos_2026.csv"
    if not pontos_csv.exists():
        pontos_csv = BASE_DIR / "roteiro_tatico_visitas_pontos_2026.csv"

    pontos_geo = []
    if pontos_csv.exists():
        pdf = pd.read_csv(pontos_csv, sep=';', low_memory=False)
        for _, pr in pdf.iterrows():
            lat = pr.get('latitude')
            lon = pr.get('longitude')
            if pd.notna(lat) and pd.notna(lon):
                try:
                    pontos_geo.append({
                        "id": str(pr.get('Ponto_Numero', '')),
                        "end": str(pr.get('Endereco_Completo', '')),
                        "lat": float(lat),
                        "lon": float(lon),
                        "cap": int(pr.get('Capacidade_Total_Vagas', 0)) if pd.notna(pr.get('Capacidade_Total_Vagas')) else 0
                    })
                except Exception:
                    pass
    print(f"Indexados {len(pontos_geo):,} pontos de táxi DTP para calcular proximidade aos edifícios corporativos.")

    records = []
    for idx, c in enumerate(CURATED_CORPORATE, start=1):
        lat = c['lat']
        lon = c['lon']
        dist = haversine(CHAME_LAT, CHAME_LON, lat, lon)

        # Encontrar ponto de táxi DTP mais próximo
        closest_ponto = "Ponto na via pública (< 500m)"
        ponto_dist_min = 999.0
        ponto_id_found = ""
        for p in pontos_geo:
            pd_km = haversine(lat, lon, p['lat'], p['lon'])
            if pd_km < ponto_dist_min:
                ponto_dist_min = pd_km
                ponto_id_found = p['id']
                dist_m = int(pd_km * 1000)
                closest_ponto = f"Ponto {p['id']} - {p['end']} ({p['cap']} vagas a {dist_m}m)"

        # Determinar Tier de Potencial Comercial Corporativo
        # Tier A: > 1.000 colaboradores presenciais ou Big Techs/Bancos Globais
        # Tier B: 300 a 1.000 colaboradores
        # Tier C: 100 a 300 colaboradores
        colab_num = 0
        if "Mais de 5.000" in c['faixa_colab'] or "2.500 a 5.000" in c['faixa_colab'] or "1.000 a 2.500" in c['faixa_colab']:
            tier_comercial = "Tier A - Mega Corporação (> 1.000 presenciais)"
            score_b2b = 96 if dist <= 3.5 else 90
            est_corridas = "1.500 a 5.000 corridas/mês"
        elif "500 a 1.000" in c['faixa_colab'] or "250 a 500" in c['faixa_colab']:
            tier_comercial = "Tier B - Grande Empresa (300 a 1.000 presenciais)"
            score_b2b = 88 if dist <= 3.5 else 82
            est_corridas = "600 a 1.500 corridas/mês"
        else:
            tier_comercial = "Tier C - Médio Porte (100 a 300 presenciais)"
            score_b2b = 80 if dist <= 3.5 else 74
            est_corridas = "200 a 600 corridas/mês"

        tempo_min = max(3, int(dist * 2.2) + 2)

        records.append({
            "ID_Prospect_B2B": f"CORP-{idx:03d}",
            "Nome_Empresa": c['nome'],
            "Razao_Social_Holding": c['razao'],
            "Setor_Economico": c['setor'],
            "Qtd_Colaboradores_Presenciais_Est": c['colaboradores_est'],
            "Faixa_Colaboradores": c['faixa_colab'],
            "Edificio_Sede_Complexo": c['edificio'],
            "Endereco_Completo": f"{c['logradouro']}, {c['numero']}, {c['bairro']}, São Paulo - SP, CEP {c['cep']}",
            "Logradouro": c['logradouro'],
            "Numero": c['numero'],
            "Bairro": c['bairro'],
            "CEP": c['cep'],
            "Latitude": lat,
            "Longitude": lon,
            "Distancia_Sede_Chame_Taxi_km": dist,
            "Tempo_Estimado_Deslocamento_min": tempo_min,
            "Ponto_Taxi_Mais_Proximo": closest_ponto,
            "Demanda_Vouchers_Horas_Extras_Noturno": c['vouchers_noturno'],
            "Demanda_Viagens_Aeroportos": c['viagens_aeroportos'],
            "Demanda_Frota_ESG_Eletrica": c['demanda_esg'],
            "Vantagem_Faixa_Onibus_Reunioes": c['faixa_onibus'],
            "Estimativa_Potencial_Corridas_Mes": est_corridas,
            "Tier_Potencial_Comercial": tier_comercial,
            "Score_Afinidade_Chame_Taxi": score_b2b,
            "Script_Pitch_Comercial_Chame_Taxi": c['pitch'],
            "Telefone_Central": c['telefone'],
            "Website_Corporativo": c['website']
        })

    df = pd.DataFrame(records)
    # Ordenar por Distância da sede Chame Táxi
    df.sort_values(by=['Distancia_Sede_Chame_Taxi_km', 'Score_Afinidade_Chame_Taxi'], ascending=[True, False], inplace=True)
    df.reset_index(drop=True, inplace=True)
    # Reindexar ID_Prospect_B2B
    for i in range(len(df)):
        df.at[i, 'ID_Prospect_B2B'] = f"CORP-{i+1:03d}"

    print(f"\nEmpresas mapeadas e estruturadas: {len(df):,}")
    print("\nDistribuição por Tier:")
    print(df['Tier_Potencial_Comercial'].value_counts())
    print("\nDistribuição por Faixa de Colaboradores:")
    print(df['Faixa_Colaboradores'].value_counts())
    print("\nTop 10 Empresas mais próximas da Cooperativa Chame Táxi:")
    for _, r in df.head(10).iterrows():
        print(f" -> {r['Distancia_Sede_Chame_Taxi_km']:4.2f} km | {r['Nome_Empresa']} ({r['Bairro']}) - {r['Qtd_Colaboradores_Presenciais_Est']}")

    # Salvar em CSV e Excel na pasta 'Novos Alvarás 2026' e raiz
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    df.to_csv(OUTPUT_CSV, sep=';', index=False, encoding='utf-8-sig')
    df.to_excel(OUTPUT_XLSX, index=False, engine='openpyxl')

    df.to_csv(ROOT_CSV, sep=';', index=False, encoding='utf-8-sig')
    df.to_excel(ROOT_XLSX, index=False, engine='openpyxl')

    print(f"\nArquivos salvos:")
    print(f" -> {OUTPUT_CSV}")
    print(f" -> {OUTPUT_XLSX}")
    print(f" -> {ROOT_CSV}")
    print(f" -> {ROOT_XLSX}")

if __name__ == '__main__':
    main()
